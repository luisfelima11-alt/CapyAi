const decks = themes.map(([lessonId, title, emoji]) => {
    const lesson = JSON.parse(read(`data/lessons/${lessonId}.json`));
    if (lesson.id !== lessonId || lesson.lang !== 'en') throw new Error(`Invalid source lesson ${lessonId}`);
    const terms = [];
    for (const item of lesson.vocab) {
        const word = item.en?.trim();
        const translation = item.pt?.trim();
        if (!word || !translation || /[<>]/.test(word + translation)) continue;
        const key = normalize(word);
        if (!key || seen.has(key)) continue;
        seen.add(key);
        terms.push([word, translation]);
        if (terms.length === 20) break;
    }
    if (terms.length !== 20) throw new Error(`${title}: only ${terms.length} unique terms`);
    return [`en-lesson-${lessonId}`, title, emoji, 'en', lessonId, terms];
});

const englishTotal = Object.values(existing).reduce((n, deck) => n + deck.cards.length, 0) +
    [...courses, ...decks].filter(deck => deck[3] === 'en').reduce((n, deck) => n + deck[5].length, 0);
if (englishTotal !== 1000) throw new Error(`Expected 1000 English cards, got ${englishTotal}`);
const output = '// Generated by scripts/build-english-flashcards.js from the English lesson catalog.\n' +
    'const ENGLISH_FLASHCARD_DECKS = [\n' + decks.map(deck => `    ${JSON.stringify(deck)},`).join('\n') + '\n];\n';
fs.writeFileSync(path.join(root, 'flashcards-english.js'), output);
